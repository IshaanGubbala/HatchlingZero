#!/usr/bin/env python3
"""Real held-out ARC evaluation, plans/newnewplan.md section 34 Step 1b/c:
the model never sees the answer, real autoregressive byte generation,
exact grid-match accuracy (pass@1) -- teacher-forced CE is a debugging
metric only, this is the real instrument BDH-CQ's own benchmark uses.

Also implements the Step 1c paired fixed-R evaluator: the SAME frozen
set of episodes, SAME checkpoint, ONLY R varies -- unlike the earlier
LOW/MEDIUM/HIGH training eval (plans/newnewplan.md section 33, now a
historical diagnostic) which sampled DIFFERENT episodes into each band,
this is a real controlled comparison.

Real, disclosed cost note: HZ-CQ-v0 has no incremental cache (see
reference/hz0h_bdh_arc_task_memory_torch.py's own docstring -- every
phase transition recomputes full rounds over the WHOLE growing
sequence). Autoregressive generation therefore re-runs n_rounds_per_phase
full rounds for EVERY generated byte, making real generation far more
expensive than the teacher-forced training loss. --max-answer-bytes
and --dev-n exist specifically to keep a first real run tractable
locally; this is real evidence for why v1's fixed-size S/H (no growing
sequence) matters for inference cost too, not just measurement
cleanliness.
"""
from __future__ import annotations

import argparse
import json
import random
import sys
import time
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from reference.hz0h_bdh_adaptive_gate_torch import add_adaptive_gate
from reference.hz0h_bdh_arc_task_memory_torch import _embed_bytes, _full_rounds, forward_hz_cq
from reference.hz0h_bdh_vb_subspace_decoder_torch import BDHVBSubspaceDecoder, BDHVBSubspaceDecoderConfig
from scripts.hz0h_bdh_arc_task_loader import build_episode_parts, grids_equal, load_arc_tasks, parse_answer
from scripts.hz0h_bdh_width_flop_frontier_local import pick_device, synchronize


def load_checkpoint(config: BDHVBSubspaceDecoderConfig, checkpoint_path: Path, gate_hidden: int, device) -> BDHVBSubspaceDecoder:
    model = BDHVBSubspaceDecoder(config).to(device=device, dtype=torch.float32)
    add_adaptive_gate(model, hidden=gate_hidden, g_init=0.58)
    ckpt = torch.load(checkpoint_path, map_location="cpu")
    missing, unexpected = model.load_state_dict(ckpt["state_dict"], strict=True)
    assert not missing and not unexpected, f"checkpoint shape mismatch: missing={missing} unexpected={unexpected}"
    return model


@torch.no_grad()
def generate_answer(model, memory_text: str, query_text: str, n_rounds_per_phase: int,
                     n_latent_rounds: int, device, max_answer_bytes: int = 400) -> tuple[str, int]:
    """Real autoregressive generation, model never sees the answer.
    Primes with the literal 'ANSWER\\n' marker (a fixed protocol token,
    same as priming an LM with 'A:' -- not something the model needs to
    discover), then generates byte-by-byte, greedy (argmax), stopping
    on a real '\\nEND' terminator or max_answer_bytes. Returns
    (generated_text, n_bytes_generated) -- generated_text does NOT
    include the 'ANSWER\\n' prime, only what the model produced."""
    C = model.config
    D, nh = C.n_embd, C.n_head
    N = D * C.mlp_internal_dim_multiplier // nh

    _logits, _loss, x = forward_hz_cq(model, memory_text, query_text, None,
                                       n_rounds_per_phase, n_latent_rounds, device)
    B = x.shape[0]

    prime_bytes = list("ANSWER\n".encode("utf-8"))
    prime_embed = _embed_bytes(model, prime_bytes, device)
    x = torch.cat([x, prime_embed], dim=2)
    T = x.shape[2]
    x = _full_rounds(x, model, n_rounds_per_phase, B, T, D, nh, N)

    generated: list[int] = []
    for _ in range(max_answer_bytes):
        last = x[:, 0, -1, :].reshape(B, D)
        logits = last @ model.lm_head
        next_byte = int(logits.argmax(dim=-1).item())
        generated.append(next_byte)
        if len(generated) >= 4 and bytes(generated[-4:]) == b"\nEND":
            break
        new_embed = _embed_bytes(model, [next_byte], device)
        x = torch.cat([x, new_embed], dim=2)
        T = x.shape[2]
        x = _full_rounds(x, model, n_rounds_per_phase, B, T, D, nh, N)

    text = bytes(generated).decode("utf-8", errors="replace")
    return text, len(generated)


def evaluate_pass1(model, tasks: dict, task_ids: list[str], n_rounds_per_phase: int,
                    n_latent_rounds: int, device, max_answer_bytes: int, seed: int) -> dict:
    """Real exact-match pass@1 over a fixed set of tasks at a fixed R.
    Reports accuracy, malformed-output rate, mean generated bytes, and
    mean wall-clock per example -- all real, all needed to interpret
    the accuracy number honestly."""
    rng = random.Random(seed)
    correct = 0
    malformed = 0
    total_bytes = 0
    total_time = 0.0
    n = len(task_ids)
    for tid in task_ids:
        task = tasks[tid]
        mem_text, query_text, _answer_text, true_out = build_episode_parts(task, rng)
        t0 = time.perf_counter()
        gen_text, n_bytes = generate_answer(model, mem_text, query_text, n_rounds_per_phase,
                                             n_latent_rounds, device, max_answer_bytes)
        total_time += time.perf_counter() - t0
        total_bytes += n_bytes
        parsed = parse_answer("ANSWER\n" + gen_text)
        if parsed is None:
            malformed += 1
        elif grids_equal(parsed, true_out):
            correct += 1
    return {
        "R": n_latent_rounds, "n": n, "pass1_accuracy": correct / n,
        "malformed_rate": malformed / n, "mean_generated_bytes": total_bytes / n,
        "mean_seconds_per_example": total_time / n,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--init-checkpoint", type=Path,
                         default=Path("results/local/hz0h_bdh_hzcq_arc_finetune_checkpoint.pt"))
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--device", default="auto")
    parser.add_argument("--split", choices=["training", "evaluation"], default="evaluation")
    parser.add_argument("--dev-n", type=int, default=5, help="number of frozen dev episodes, paired across every R")
    parser.add_argument("--r-values", type=int, nargs="+", default=[0, 2, 4, 8, 16])
    parser.add_argument("--max-answer-bytes", type=int, default=400)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--n-embd", type=int, default=2128)
    parser.add_argument("--mult", type=int, default=16)
    parser.add_argument("--n-layer", type=int, default=8)
    parser.add_argument("--n-head", type=int, default=8)
    parser.add_argument("--d-state", type=int, default=532)
    parser.add_argument("--subspace-rank", type=int, default=64)
    parser.add_argument("--gate-hidden", type=int, default=16)
    args = parser.parse_args()

    device = pick_device(args.device)
    config = BDHVBSubspaceDecoderConfig(
        n_layer=args.n_layer, n_embd=args.n_embd, n_head=args.n_head,
        mlp_internal_dim_multiplier=args.mult, vocab_size=256, dropout=0.0,
        d_state=args.d_state, subspace_rank=args.subspace_rank,
    )
    model = load_checkpoint(config, args.init_checkpoint, args.gate_hidden, device)
    model.eval()

    tasks = load_arc_tasks(args.split)
    rng = random.Random(args.seed)
    task_ids = sorted(tasks.keys())
    rng.shuffle(task_ids)
    dev_ids = task_ids[:args.dev_n]  # SAME frozen episodes for every R below
    print(f"[hzcq_arc_eval] paired dev set: {dev_ids}", flush=True)

    results = []
    for r in args.r_values:
        started = time.perf_counter()
        result = evaluate_pass1(model, tasks, dev_ids, args.n_layer, r, device,
                                 args.max_answer_bytes, seed=args.seed)
        elapsed = time.perf_counter() - started
        result["wall_clock_s"] = elapsed
        results.append(result)
        print(f"[hzcq_arc_eval] R={r}: {result}", flush=True)

    synchronize(device)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps({
        "dev_ids": dev_ids, "split": args.split, "init_checkpoint": str(args.init_checkpoint),
        "results": results,
    }, indent=2), encoding="utf-8")
    print(f"[done] wrote {args.out}", flush=True)


if __name__ == "__main__":
    main()
